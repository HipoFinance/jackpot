// docs/message-graphs.md: per chapter a title, a few lines of text, the graphs, and the Jackpot's numbers after it
// under their names in the code, with what changed in bold. Each graph is a <picture> that GitHub shows by theme.
import { GROUPS, TITLES, captions } from './captions'
import { ChapterGraph, nano, rate } from './dot'
import { TraceChapter, TraceState } from './types'

const ROWS: [string, string][] = [
    ['held', 'held_tokens'],
    ['reserved', 'reserved_tokens'],
    ['free', 'free_tokens'],
    ['pot', 'pot, at the stored rate'],
    ['principal', 'principal'],
    ['float', 'float, GRAM'],
]

const plain = (html: string) =>
    html
        .replace(/<code>(.*?)<\/code>/g, '`$1`')
        .replace(/<strong>(.*?)<\/strong>/g, '**$1**')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')

const rateOf = (a: TraceState) => rate(String(a.quote_coins), String(a.quote_tokens))
const num2 = (x: string | number | boolean | string[]) => nano(String(x), 2)

function counters(a: TraceState, prev: TraceState | null): string {
    const cells: [string, string, boolean][] = ROWS.map(([k, lab]) => [lab, num2(a[k]), prev != null && num2(prev[k]) !== num2(a[k])])
    cells.push(['stored rate', rateOf(a), prev != null && rateOf(prev) !== rateOf(a)])
    cells.push(['draw', String(a.state), prev != null && prev.state !== a.state])
    cells.push(['tag', String(a.tag), prev != null && prev.tag !== a.tag])
    const bold = (v: string, c: boolean) => (c ? `**${v}**` : v)
    const head = `| ${cells.map((c) => c[0]).join(' | ')} |\n|${cells.map(() => ' ---: ').join('|')}|\n`
    const row = `| ${cells.map((c) => bold(c[1], c[2])).join(' | ')} |`
    const who: string[] = []
    for (const p of ['alice', 'bob', 'carol', 'dave', 'eve', 'frank']) {
        const cap = p.charAt(0).toUpperCase() + p.slice(1)
        const j = String(a[`${p}_jgram`])
        const pj = prev == null ? '0' : String(prev[`${p}_jgram`])
        if (BigInt(j) > 0n || BigInt(pj) > 0n) who.push(j !== pj ? `**${cap} ${num2(j)}**` : `${cap} ${num2(j)}`)
        const j2 = String(a[`${p}_jgram2`] ?? '0')
        const pj2 = prev == null ? '0' : String(prev[`${p}_jgram2`] ?? '0')
        if (BigInt(j2) > 0n || BigInt(pj2) > 0n) {
            who.push(j2 !== pj2 ? `**${cap} ${num2(j2)} in the new Jackpot**` : `${cap} ${num2(j2)} in the new Jackpot`)
        }
    }
    const nodes = a.nodes as string[]
    const standing = nodes.filter((x) => x === 'active').length
    const extra: string[] = []
    if (prev != null && standing !== (prev.nodes as string[]).filter((x) => x === 'active').length) extra.push(`**tree nodes left: ${String(standing)}**`)
    if (prev != null && a.retired !== prev.retired) extra.push('**retired**')
    return `${head}${row}\n\njGRAM: ${who.length > 0 ? who.join(', ') : 'nobody'}${extra.length > 0 ? ', ' + extra.join(', ') : ''}\n`
}

export function buildMarkdown(chapters: TraceChapter[], graphs: Map<string, ChapterGraph[]>): string {
    const text = captions(chapters)
    const byId = new Map(chapters.map((c) => [c.id, c]))
    const o: string[] = []
    o.push('# Jackpot message graphs')
    o.push(
        "Generated by `npm run graphs` from a sandbox run of the amended contracts against Hipo's real contracts (`tests/story/story.spec.ts`). Do not edit by hand. The graphs carry the operation and its token and principal amounts; no GRAM value, `query_id` or logical time, so they do not move with gas prices.",
    )
    o.push(
        "One story from start to finish: players deposit, Hipo's reward lands, a poke makes a boundary that fixes the pot, drand picks three winners, players leave, and at the end the Jackpot moves its last player to a successor, burns what is left and closes its tree. The number on an arrow is the order of its message in the chapter. Arrows with the same sender, receiver and operation are drawn once, with all their numbers. Under each graph are the Jackpot's numbers after that step, under their names in the code, with what changed in bold. The pot is shown at the stored rate, the rate of the last poke.",
    )
    o.push(
        'Boxes: the Jackpot, jGRAM wallets, hGRAM wallets, tree nodes, Hipo\'s contracts, another jetton\'s wallet, and people. Blue arrows move tokens, dashed arrows are returned GRAM (`gas_excess`), red arrows are a bounce or a failure.',
    )
    let c = 1
    const num = new Map<string, number>()
    o.push('## Chapters')
    for (const [g, ids] of GROUPS) {
        o.push(`**${g}**`)
        o.push(
            ids
                .map((id) => {
                    num.set(id, c)
                    return `${String(c++)}. [${TITLES[id]}](#${id})`
                })
                .join('\n'),
        )
    }
    let prev: TraceState | null = null
    for (const [g, ids] of GROUPS) {
        o.push(`## ${g}`)
        for (const id of ids) {
            const ch = byId.get(id)
            const ps = text[id] as string[] | undefined
            if (ch == null || ps == null) throw new Error(`chapter ${id} missing`)
            o.push(`<a id="${id}"></a>\n\n### ${String(num.get(id))}. ${TITLES[id]}`)
            o.push(ps.slice(0, 2).map(plain).join('\n\n'))
            for (const gr of graphs.get(id) ?? []) {
                if (gr.title) o.push(`**${gr.title}**`)
                const alt = `${TITLES[id]}${gr.title ? ': ' + gr.title : ''}`.replace(/"/g, "'")
                o.push(
                    `<picture>\n  <source media="(prefers-color-scheme: dark)" srcset="graphs/${gr.name}-dark.svg">\n  <img alt="${alt}" src="graphs/${gr.name}-light.svg">\n</picture>`,
                )
            }
            if (ps.length > 2) o.push(ps.slice(2).map(plain).join('\n\n'))
            o.push(counters(ch.after, prev))
            prev = ch.after
        }
    }
    o.push(
        "## Run details\n\nThe amended contracts against Hipo's real contracts in the sandbox, with mainnet's global version, so bounceable messages ask for full-body bounces. Hipo's rate starts at 1 here, and each reward is a gift of 0.031% to Hipo's treasury. `min_gap` is the spec's 32,768 s and `rise_min` its 50 ppm. The drand check is the test build, which skips the pairing; the seed is made from the signature and the block hash as in production. The burn batch is 5 hGRAM instead of 50, so a burn shows up. The float was set by hand twice: to 7.5 GRAM before the boundary, so that it unstakes, and to 3.5 GRAM before the refill. Each player's hGRAM was minted before chapter 1. The foreign jetton is Hipo's wallet code under a stand-in minter, and the successor is a second Jackpot built from the same code.",
    )
    return o.join('\n\n') + '\n'
}
